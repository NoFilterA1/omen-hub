def t(key: str) -> str:
    lang = _settings.get_language()
    return _TR.get(lang, {}).get(key) or _TR["en"].get(key, key)


def available() -> list[tuple[str, str]]:
    """(label, code) pairs for a language selector."""
    return [("English", "en"), ("Русский", "ru"), ("Nederlands", "nl")]
